<?php
/**
 * A verified INSERT containing literal rows for one expected table.
 *
 * @package BackupsForRestic
 */

declare( strict_types=1 );

namespace BackupsForRestic\Database\Restore;

use BackupsForRestic\Database\Dump\SqlFormatter;
use BackupsForRestic\Exception\FormatException;

defined( 'ABSPATH' ) || exit;

/**
 * Rewrites only the table identifier. No expression, subquery, modifier or trailing clause
 * can reach the database, and value bytes retain the dump writer's exact escaping.
 */
final readonly class InsertStatement {

	/** The dump writer's largest page, even when every row is very small. */
	public const int MAX_ROWS = 20000;

	/**
	 * Records a checked batch.
	 *
	 * @param string       $sql     INSERT into the caller's shadow table.
	 * @param list<string> $columns Quoted columns in their original order.
	 * @param int          $rows    Number of literal tuples.
	 */
	private function __construct( public string $sql, public array $columns, public int $rows ) {
	}

	/**
	 * Validates the complete statement before changing its destination.
	 *
	 * @param string $sql    One line from a table dump.
	 * @param string $source Table named by the validated manifest.
	 * @param string $shadow Shadow name generated by the importer, never by the dump.
	 * @return self Batch safe to execute with the dump's SQL mode.
	 * @throws FormatException If anything other than literal rows for this table is present.
	 */
	public static function parse( string $sql, string $source, string $shadow ): self {
		$lexer = new SqlLexer( $sql );
		$lexer->expect( 'INSERT' );
		$lexer->expect( 'INTO' );
		$table = $lexer->identifier();
		if ( $table->value !== $source || '' === $shadow || strpbrk( $shadow, "\0\r\n" ) !== false ) {
			throw new FormatException( 'A database dump INSERT names an unexpected table.' );
		}
		$lexer->expect( '(' );
		$columns = [];
		$seen    = [];
		if ( $lexer->peek()?->is( ')' ) ?? false ) {
			$lexer->next();
		} else {
			do {
				$name = $lexer->identifier()->value;
				if ( isset( $seen[ $name ] ) || count( $columns ) >= 4096 ) {
					throw new FormatException( 'A database dump INSERT has duplicate or too many columns.' );
				}
				$seen[ $name ] = true;
				$columns[]     = $name;
				$delimiter     = $lexer->next();
			} while ( $delimiter?->is( ',' ) ?? false );
			if ( ! ( $delimiter?->is( ')' ) ?? false ) ) {
				throw new FormatException( 'A database dump INSERT has an invalid column list.' );
			}
		}
		$lexer->expect( 'VALUES' );
		$rows = 0;
		do {
			if ( ++$rows > self::MAX_ROWS ) {
				throw new FormatException( 'A database dump INSERT exceeds its row batch limit.' );
			}
			$lexer->expect( '(' );
			foreach ( $columns as $position => $column ) {
				if ( $position > 0 ) {
					$lexer->expect( ',' );
				}
				$value = $lexer->next();
				if ( null === $value || ( ! in_array( $value->kind, [ SqlToken::STRING, SqlToken::NUMBER ], true ) && ! $value->is( 'NULL' ) ) ) {
					throw new FormatException( 'A database dump INSERT contains an expression instead of a literal value.' );
				}
			}
			$lexer->expect( ')' );
			$more = $lexer->peek()?->is( ',' ) ?? false;
			if ( $more ) {
				$lexer->next();
			}
		} while ( $more );
		$lexer->end();
		return new self( 'INSERT INTO ' . SqlFormatter::identifier( $shadow ) . substr( $sql, $table->end ), $columns, $rows );
	}
}
